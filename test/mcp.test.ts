import assert from 'node:assert/strict';
import { after, before, test } from 'node:test';
import { existsSync } from 'node:fs';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

const root = process.cwd();
let client: Client;
let dir: string;

before(async () => {
  dir = await mkdtemp(path.join(os.tmpdir(), 'beauty-mcp-'));
  const transport = new StdioClientTransport({
    command: process.execPath,
    args: [path.join(root, 'dist', 'mcp', 'server.js')],
    cwd: dir,
  });
  client = new Client({ name: 'beauty-mcp-test', version: '1.0.0' });
  await client.connect(transport);
});

after(async () => {
  await client.close();
  await rm(dir, { recursive: true, force: true });
});

test('exposes the full tool surface', async () => {
  const { tools } = await client.listTools();
  const names = tools.map((tool) => tool.name).sort();
  assert.deepEqual(names, [
    'beauty_create_deck',
    'beauty_create_experience',
    'beauty_create_gif',
    'beauty_create_page',
    'beauty_create_sprint',
    'beauty_create_story',
    'beauty_examples',
    'beauty_get_skill',
    'beauty_get_style',
    'beauty_list_styles',
    'beauty_validate',
  ]);
});

test('styles expose exact fonts and palette', async () => {
  const result = await client.callTool({ name: 'beauty_get_style', arguments: { style: 'renaissance' } });
  const text = (result.content as Array<{ type: string; text: string }>)[0]?.text ?? '';
  assert.match(text, /EB Garamond/);
  assert.match(text, /#B4432C/);
  assert.match(text, /0–2 px/);
});

test('creates and audits a page over MCP', async () => {
  const result = await client.callTool({
    name: 'beauty_create_page',
    arguments: {
      style: 'papercraft',
      title: 'MCP Garden',
      tagline: 'A page created over the protocol.',
      intro: 'Paper, scissors and a protocol. This page was generated by a tool call.',
      output: 'out/mcp-page.html',
    },
  });
  const text = (result.content as Array<{ type: string; text: string }>)[0]?.text ?? '';
  assert.match(text, /Created a Paper Craft page/);
  assert.match(text, /A \(100\/100\)/);
  assert.ok(existsSync(path.join(dir, 'out', 'mcp-page.html')));

  const audit = await client.callTool({
    name: 'beauty_validate',
    arguments: { style: 'papercraft', path: 'out/mcp-page.html' },
  });
  const auditText = (audit.content as Array<{ type: string; text: string }>)[0]?.text ?? '';
  assert.match(auditText, /A · 100\/100/);
});

test('creates a valid GIF over MCP', async () => {
  const result = await client.callTool({
    name: 'beauty_create_gif',
    arguments: {
      style: 'brutalist',
      text: 'MCP TEST',
      subtitle: 'NO SOFT EDGES',
      template: 'loop',
      width: 320,
      height: 320,
      fps: 10,
      duration: 1,
      output: 'out/mcp.gif',
    },
  });
  const text = (result.content as Array<{ type: string; text: string }>)[0]?.text ?? '';
  assert.match(text, /Created a Brutalist GIF/);
  const file = await readFile(path.join(dir, 'out', 'mcp.gif'));
  assert.equal(file.subarray(0, 6).toString('ascii'), 'GIF89a');
});
